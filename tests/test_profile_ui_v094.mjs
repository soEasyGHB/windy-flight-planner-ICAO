import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {buildRouteProfile,PROFILE_LEVELS} from './generated/profileChart.js';
const src=readFileSync('src/plugin.svelte','utf8');
const markup=src.slice(0,src.indexOf('<script lang="ts">'));
const main=markup.slice(markup.indexOf('<div class="fr-main-stack">'),markup.indexOf('<details class="fr-settings">'));
const panel=markup.slice(markup.indexOf('{#if profileOpen}'));
assert(!main.includes('id="fr-flight-level"'));
assert(main.includes('on:click={openWeatherProfile}'));
assert(main.indexOf('id="fr-etd-date"') < main.indexOf('id="fr-etd-time"'));
assert(main.indexOf('fr-section-our-planner') < main.indexOf('fr-section-export'));
assert(!main.includes('id="fr-tas"'));
assert(!panel.includes('fr-profile-sidebar'));
assert(!panel.includes('fr-profile-legend'));
assert(panel.includes('fr-profile-flight-summary'));
for(const label of ['ETD UTC','Расстояние','Расчётное время','эшелон','Тропопауза'])assert(panel.includes(label));
assert(panel.includes('{waypoint.label}'), 'Every waypoint code must be rendered, not an index only');
assert(!panel.includes('{#if waypoint.showCode}'), 'No waypoint names can be suppressed');
assert(!panel.includes('fr-waypoint-number'));
assert(panel.includes('fr-waypoint-nameplate'));
assert(panel.includes('profileViz.tropopauseDescription'));
assert(panel.includes('profileViz.tropopauseLabel'));
assert(src.includes('localStorage.setItem(SAVED_FLIGHT_KEY'));
assert(src.includes('JSON.stringify({routeText,etdDate,etdTime})'));
assert(!src.includes('function flightLevelChanged('));
assert(src.includes('fl=even?.fl??360')); 
const cell={temp:-43,rh:10,windKt:48,windDir:260,cloud:5,cape:0,isaDeviationC:12,indicators:[]};
const mk=(i,d,tropopauseFL)=>({sample:{label:`FIX${String(i).padStart(2,'0')}`,lat:40+i*.1,lon:15+i*.1,distanceNm:d,eta:new Date(Date.UTC(2026,10,12,16)+d/450*3600000)},
  flightLevels:Object.fromEntries(PROFILE_LEVELS.map(fl=>[fl,cell])),levels:{},flPressure:250,atFl:cell,tropopauseFL,alerts:[]});
const clustered=Array.from({length:14},(_,i)=>mk(i,i===13?1000:i*2,i<3?420:i>=11?318:365));
const profile=buildRouteProfile(clustered,380);
assert.equal(profile.waypoints.length,14);
assert(profile.waypoints.every(w=>w.label&&Number.isFinite(w.labelX)&&Number.isFinite(w.labelY)));
assert(new Set(profile.waypoints.map(w=>w.label)).size===14);
assert(profile.waypoints.filter(w=>w.labelY!==profile.waypoints[0].labelY).length>0,'Labels must use staggered rows');
assert.equal(profile.selectedFl,380);
assert(profile.tropopauseSegments.length>0,'Connected estimates should show clipped visible tropopause');
assert(profile.tropopauseSegments.every(seg=>seg.every(p=>p.y>=profile.tropopauseBandTop&&p.y<=profile.tropopauseBandBottom))); 
const nowhere=buildRouteProfile([mk(0,0,null),mk(1,20,null)],380);
assert.equal(nowhere.hasTropopause,false);
assert.match(nowhere.tropopauseDescription,/нет достаточных данных/);
console.log('PASS: automatic even/odd FL, five-block layout, full staggered FIX names, footer ETD/distance, full-range tropopause');
