import assert from 'node:assert/strict';
import {loadDemo,importCsv,parseRoute,mapLabelPoints,importAirwaysCsv} from './generated/navdb.js';
import {makeRouteGpx,buildWindyPlannerRequest,routeIssues} from './generated/routePlanner.js';
loadDemo();
let route=parseRoute('EHAM DCT EDDF DCT LTFM');
assert.equal(route.segments.length,1);
assert.equal(route.gaps.length,0);
assert.equal(mapLabelPoints(route).length,3);
assert.equal(buildWindyPlannerRequest(route).params.view,'ifr');
assert.equal(buildWindyPlannerRequest(route).params.coords.length,3);
assert.equal((makeRouteGpx(route).match(/<trkseg>/g)||[]).length,1);
route=parseRoute('EHAM NOTHERE EDDF LTFM');
assert(route.unresolved.includes('NOTHERE'));
assert(route.gaps.length>=1);
assert(routeIssues(route).length);
assert.throws(()=>buildWindyPlannerRequest(route),/Неполный/);
assert.equal(buildWindyPlannerRequest(route,true).partial,true);
const xml=makeRouteGpx(route,{allowPartial:true});
assert.match(xml,/PARTIAL/);
assert.equal((xml.match(/<trkseg>/g)||[]).length,1);
importCsv('ident,latitude_deg,longitude_deg,type\nFIRSTX,51.0,10.0,FIX\nLASTXX,53.0,14.0,FIX\n');
importAirwaysCsv('airway,segment,seq,latitude_deg,longitude_deg\nA551,seg1,0,51,10\nA551,seg1,1,52,12\nA551,seg1,2,53,14\n');
route=parseRoute('FIRSTX A551 LASTXX');
assert.equal(route.gaps.length,0);
assert.equal(route.expandedAirways[0],'A551');
assert.equal(mapLabelPoints(route).length,2);
assert(route.points.some(p=>p.showLabel===false));
assert(!makeRouteGpx(route).includes('A551-1</name></wpt>'));
// Ident collision: A551 could be a navaid as well as the actual ATS label.
importCsv('ident,latitude_deg,longitude_deg,type\nA551,41.0,-73.0,VOR\n');
route=parseRoute('FIRSTX A551 LASTXX');
assert.equal(route.expandedAirways[0],'A551');
assert.equal(route.points.filter(p=>p.showLabel).length,2);
assert(route.points.every(p=>p.lon>0),'No false jump to an ident collision in the USA');
console.log('PASS: route planner handoff, GPX, missing legs and ATS labels');
