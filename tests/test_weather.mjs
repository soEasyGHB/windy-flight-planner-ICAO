import assert from 'node:assert/strict';
import {loadDemo,parseRoute,importCsv} from './generated/navdb.js';
import {generateWaypointSamples,interpolatePressure,FLIGHT_LEVELS,flToHpa,isaTemperatureC} from './generated/weather.js';
loadDemo();
const date=new Date('2026-11-12T10:00:00Z');
const route=parseRoute('EHAM DCT EDDF DCT LTFM');
const samples=generateWaypointSamples(route.points,date,450);
assert.deepEqual(samples.map(s=>s.label),['EHAM','EDDF','LTFM']);
assert(samples[1].eta>samples[0].eta);
assert(samples[2].distanceNm>samples[1].distanceNm);
assert.equal(FLIGHT_LEVELS.length,11);
assert(flToHpa(350)>200 && flToHpa(350)<300);
assert(isaTemperatureC(350)<-50);
const cell=(windDir)=>({temp:-50,windKt:80,windDir,rh:40,cloud:0,cape:0,isaDeviationC:0,indicators:[]});
const blended=interpolatePressure({200:cell(350),300:cell(10)},250,350);
assert(blended.windDir!==null && (blended.windDir<15||blended.windDir>345));
assert(blended.temp!==null);
console.log('PASS: named waypoint ETAs, FL300–400, wind direction, ISA');
