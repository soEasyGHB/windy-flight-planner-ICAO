import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {convertXPlane} from './generated/xplane.js';
import {parseRoute,loadLocalXPlaneSnapshot,airwayCount} from './generated/navdb.js';
const prefix=new URL('./fixtures/xplane/',import.meta.url);
const load=(name)=>readFileSync(new URL(name,prefix),'utf8');
const base={fix:load('earth_fix.dat'),nav:load('earth_nav.dat'),awy:load('earth_awy.dat')};
const result=convertXPlane(base);
assert.equal(result.cycle,'2611');
assert.equal(result.pointCount,7);
assert.equal(result.airwayEdges,4);
assert.equal(result.rejectedEdges,0);
assert.ok(result.pointsCsv.includes('AAAXX,52,10,FIX'));
assert.ok(result.pointsCsv.includes('VORX,53.5,15,VOR'));
assert.ok(result.airwaysCsv.includes('J77'));
const loaded=loadLocalXPlaneSnapshot(result.pointsCsv,result.airwaysCsv);
assert.equal(loaded.airwayVertices,8);
assert.equal(airwayCount(),2);
const route=parseRoute('AAAXX J77 VORX');
assert.deepEqual(route.unresolved,[]);
assert.deepEqual(route.airwayNames,[]);
assert.deepEqual(route.expandedAirways,['J77']);
assert.ok(route.points.length>=4);
assert.throws(()=>convertXPlane({...base,nav:base.nav.replace('data cycle 2611','data cycle 2612')}),/AIRAC/);
assert.throws(()=>convertXPlane({...base,awy:base.awy.replaceAll('AAAXX','ZZZZZ').replaceAll('MIDXX','YYYYY').replaceAll('BBBYY','XXXXX').replaceAll('VORX','WWWWW')}),/трасс/);
console.log('PASS: X-Plane 11/12 FIX/NAV/AWY parsing, region lookup, cycle guard, airway graph');
