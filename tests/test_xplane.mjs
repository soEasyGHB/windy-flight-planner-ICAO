import assert from 'node:assert/strict';
import {xplaneCycle,assertMatchingCycles,parseXPlaneFix,parseXPlaneNav,parseXPlaneAirways} from './generated/xplane.js';
const fix='I\n1101 Version - data cycle 2607, build 2026\n52.1 7.2 TOGMO EH ENRT\n52.3 7.5 ABAGI EH ENRT\n99\n';
assert.equal(xplaneCycle(fix),'2607');
assert.equal(assertMatchingCycles([fix,fix]),'2607');
assert.throws(()=>assertMatchingCycles([fix,fix.replace('2607','2608')]),/mismatch/i);
assert.equal(parseXPlaneFix(fix).length,2);
const nav='I\n1101 Version\n3 52.12 7.12 10 11390 40 0 VORX EH TEST\n';
assert.equal(parseXPlaneNav(nav)[0].ident,'VORX');
const awy='TOGMO 52.1 7.2 ABAGI 52.3 7.5 1 100 460 M56';
assert.equal(parseXPlaneAirways(awy)[0].airway,'M56');
console.log('PASS: X-Plane parsing, cycle consistency');
