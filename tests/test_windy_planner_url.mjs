import assert from 'node:assert/strict';
import {loadDemo,importCsv,parseNamedFixRoute} from './generated/navdb.js';
import {buildWindyPlannerUrl} from './generated/windyPlannerUrl.js';

loadDemo();
importCsv('ident,latitude_deg,longitude_deg,type\nUNNT,55.0126,82.6507,AIRPORT\nABAGI,54.2,40.0,FIX\nKUDAS,40.1,45.0,FIX\nFSIA,-4.6743,55.5218,AIRPORT\n');
const route=parseNamedFixRoute('UUEE24C DCT UNNT25');
const exact=buildWindyPlannerUrl(route,'2026-11-16T18:00:00Z');
assert.equal(exact.url,'https://www.windy.com/route-planner/ifr/55.9726,37.4146;55.0126,82.6507?2026-11-16-18');
assert.equal(exact.urlTimeUtc,'2026-11-16-18');
assert.equal(exact.outsideDocumentedSlot,false);
assert.equal(exact.partial,false);
assert.equal(exact.pointsSent,2);
assert.equal(exact.from,'UUEE');assert.equal(exact.to,'UNNT');
const hour=buildWindyPlannerUrl(route,'2026-11-16T05:01:00Z');
assert.equal(hour.urlTimeUtc,'2026-11-16-05');
assert(hour.url.endsWith('?2026-11-16-05'));
assert.equal(hour.outsideDocumentedSlot,true, 'Arbitrary hours are NOT documented Windy forecast slots');
assert.equal(hour.requestedDepartureUtc,'2026-11-16T05:01:00Z');
assert.equal(hour.roundedDepartureUtc,'2026-11-16T05:00:00.000Z');
const after=buildWindyPlannerUrl(route,'2026-11-16T05:31:00Z');
assert.equal(after.urlTimeUtc,'2026-11-16-06');
assert.equal(after.outsideDocumentedSlot,false);
const half=buildWindyPlannerUrl(route,'2026-11-16T05:30:00Z');
assert.equal(half.urlTimeUtc,'2026-11-16-06','Exactly half an hour rounds forwards');
const midnight=buildWindyPlannerUrl(route,'2026-11-16T23:40:00Z');
assert.equal(midnight.urlTimeUtc,'2026-11-17-00','Rollover changes calendar date');
const unchangedMinute=buildWindyPlannerUrl(route,'2026-11-16T18:20:00Z');
assert.equal(unchangedMinute.urlTimeUtc,'2026-11-16-18');
assert.throws(()=>buildWindyPlannerUrl(route,'2026-02-30T10:00:00Z'),/UTC/);
assert.throws(()=>buildWindyPlannerUrl(route,'2026-11-16T18:00:00+03:00'),/UTC/);
const partial=parseNamedFixRoute('UUEE24C DCT ABAGI UNKNOWNFIX KUDAS DCT FSIA31');
assert(partial.gaps.length>0);
const link=buildWindyPlannerUrl(partial,'2026-11-16T18:00:00Z');
assert(link.partial);assert(link.pointsSent>=2);assert(!link.url.includes('undefined'));
const selected=partial.segments.find(s=>s.length===link.pointsSent&&s[0].ident===link.from&&s.at(-1).ident===link.to);
assert(selected,'No bridging route gaps');
assert.throws(()=>buildWindyPlannerUrl(parseNamedFixRoute('UNKNOWNONE DCT UNKNOWNTWO'),'2026-11-16T18:00:00Z'),/подтверждённого/);
console.log('PASS: nearest-hour IFR URL, exact hour, rollover, partial routes, documented-slot flag');
