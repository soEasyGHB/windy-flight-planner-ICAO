import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const src=readFileSync('src/plugin.svelte','utf8');
const alt=readFileSync('src/flightAltitude.ts','utf8');
assert(src.includes("let overlay='turbulence';"),'Default Windy overlay should be turbulence');
assert(src.includes('let fl=DEFAULT_CRUISE_FL;'),'Default flight level must come from altitude module');
assert(src.includes('for (const delay of [180,600,1300,3000])'),'Windy altitude updates must retry after late product loading');
assert(src.includes('if(requestId===altitudeRequestId) updateWindyAltitude(requestId)'),'Old retries must not overwrite new FL');
assert(src.includes('onDestroy(()=>{cancelAltitudeRetries();clearMap();});'),'Timers must be cleared when closing plugin');
assert(alt.includes("DEFAULT_TURBULENCE_RANGE = '300h-200h'"),'Default turbulence band must be 300h–200h');
assert(alt.includes("writeAndVerify(store,'levelsRange',plan.levelsRange)"),'Altitude sync must write levelsRange');
assert(alt.includes("writeAndVerify(store,'level',plan.pressureLevel)"),'Altitude sync must set center level if available');
const openHandler=src.slice(src.indexOf('export const onopen='),src.indexOf('  onMount('));
assert(openHandler.includes('setWeatherLayer();'),'Opening plugin should refresh altitude');
console.log('PASS: default FL350, turbulence 300–200h, bounded retries, range & level state verification');
