import assert from 'node:assert/strict';
import {loadDemo,importCsv,parseNamedFixRoute} from './generated/navdb.js';
import {buildNativePlannerHandoff} from './generated/nativePlannerHandoff.js';
loadDemo();
importCsv('ident,latitude_deg,longitude_deg,type\nUNNT,55.0126,82.6507,AIRPORT\nABAGI,54.2,40.0,FIX\nKUDAS,40.1,45.0,FIX\nFSIA,-4.6743,55.5218,AIRPORT\n');
const full=buildNativePlannerHandoff(parseNamedFixRoute('UUEE24C DCT UNNT25'),'2026-11-16T05:01:00Z');
assert.equal(full.timestampMs,Date.parse('2026-11-16T05:01:00Z'),'Store timestamp is exact to minute');
assert.equal(full.params.view,'ifr');
assert.deepEqual(full.params.coords,[{lat:55.9726,lon:37.4146},{lat:55.0126,lon:82.6507}]);
assert.equal(full.partial,false);assert.equal(full.verticesSent,2);
const partial=buildNativePlannerHandoff(parseNamedFixRoute('UUEE24C DCT ABAGI UNKNOWNFIX KUDAS DCT FSIA31'),'2026-11-16T18:20:00Z');
assert.equal(partial.partial,true);
assert(partial.verticesSent>=2);
assert.throws(()=>buildNativePlannerHandoff(parseNamedFixRoute('UNKNOWNONE DCT UNKNOWNTWO'),'2026-11-16T18:20:00Z'),/подтверждённого/);
assert.throws(()=>buildNativePlannerHandoff(parseNamedFixRoute('UUEE DCT UNNT'),'2026-02-30T05:01:00Z'),/UTC/);
console.log('PASS: native planner best-effort coordinates, exact store timestamp, no gap bridging');
