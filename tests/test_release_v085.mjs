import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {loadDemo,importCsv,importAirwaysCsv,parseRoute,mapLabelPoints} from './generated/navdb.js';
import {makeRouteGpx} from './generated/routePlanner.js';
loadDemo();
const o=parseRoute('UUEE24C DCT OMDB30R');
assert.deepEqual(mapLabelPoints(o).map(p=>p.ident),['UUEE','OMDB']);
assert.equal(o.unresolved.length,0);
assert.equal(o.gaps.length,0);
importCsv('ident,latitude_deg,longitude_deg,type\nFIRST,48,12,FIX\nLASTX,49,15,FIX\nY12XX,54,12,FIX\n');
importAirwaysCsv('airway,segment,seq,latitude_deg,longitude_deg\nY12,leg0,0,48,12\nY12,leg0,1,48.5,13.5\nY12,leg0,2,49,15\n');
const route=parseRoute('FIRST Y12 LASTX');
assert.deepEqual(route.airwayNames,[]);
assert.deepEqual(route.expandedAirways,['Y12']);
assert.equal(route.gaps.length,0);
assert.equal(route.points.filter(p=>p.showLabel).length,2);
const xml=makeRouteGpx(route);
assert.match(xml,/<rtept[^>]*><name>FIRST<\/name><\/rtept>/);
assert.match(xml,/<rtept[^>]*><name>LASTX<\/name><\/rtept>/);
assert.equal((xml.match(/<rtept /g)||[]).length,2);
for(const token of ['<trk','<wpt','<name>Y12','<name>Y12-'])assert(!xml.includes(token),`Unexpected GPX data ${token}`);
const p=parseRoute('UUEE24C DCT FIRST NOTHERE LASTX DCT OMDB30R');
assert(p.gaps.length>0);
// A PARTIAL GPX must never create a route between isolated disjoint segments.
const partial=makeRouteGpx(p,{allowPartial:true});
assert(partial.includes('PARTIAL'));
assert(!partial.includes('<trkpt'));
assert((partial.match(/<rte>/g)||[]).length>=1);
const src=readFileSync('src/plugin.svelte','utf8');
assert(src.includes('<option value="thunder">'));
assert(src.includes('class="fr-param-stack"'));
console.log('PASS: runway-normalized ICAO, Y12 airway, named-only GPX, no false partial joins, compact UI');
