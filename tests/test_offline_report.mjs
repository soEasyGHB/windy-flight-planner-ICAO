import assert from 'node:assert/strict';
import {buildOfflineBrief,escapeHtml} from './generated/offlineReport.js';

const p=(ident,lat,lon,index,showLabel=true,type='FIX')=>({ident,lat,lon,index,showLabel,type,source:'test'});
const a=p('ABAGI',52,40,0),mid=p('M56-2',50,43,1,false,'ATS'),b=p('NIMTA',48,46,2);
const route={points:[a,mid,b],segments:[[a,mid,b]],gaps:[],unresolved:[],skipped:[],airwayNames:[],expandedAirways:['M56'],ambiguous:[],distanceNm:350};
const base={route,routeText:'ABAGI M56 NIMTA',overlay:'thunder',model:'ecmwf',mapTimeUtc:'2026-10-27 20:00',departureUtc:'2026-10-27 18:00',tasKt:450,fl:350,forecastRows:[],createdAtUtc:'2026-10-27 18:10'};
const embedded=buildOfflineBrief({...base,image:{dataUrl:'data:image/png;base64,iVBORw0KGgo=',filename:'screen.png'}});
assert.match(embedded,/<!doctype html>/i);
assert.match(embedded,/data:image\/png;base64,iVBORw0KGgo=/);
assert.match(embedded,/Слой: Грозы/);
assert.match(embedded,/Снимок экрана/);
assert.match(embedded,/ABAGI/);
assert.match(embedded,/NIMTA/);
assert.doesNotMatch(embedded,/<text[^>]*>M56-2<\/text>/);
assert.match(embedded,/window\.print\(\)/);
assert.doesNotMatch(embedded,/<script\s+src=/);
const noShot=buildOfflineBrief({...base,image:null,overlay:'turbulence'});
assert.match(noShot,/Турбулентность/);
assert.match(noShot,/грозы и турбулентность на ней НЕ показаны/);
assert.match(noShot,/<svg/);
const escaped=buildOfflineBrief({...base,routeText:'<script>alert(1)</script>',image:null});
assert.doesNotMatch(escaped,/<script>alert/);
assert.match(escaped,/&lt;script&gt;/);
assert.equal(escapeHtml('A & "B"'), 'A &amp; &quot;B&quot;');
assert.throws(()=>buildOfflineBrief({...base,image:{dataUrl:'data:image/svg+xml;base64,abcd',filename:'x.svg'}}),/PNG, JPEG/);
assert.throws(()=>buildOfflineBrief({...base,route:{...route,segments:[]},image:null}),/двумя точками/);
const broken={...route,segments:[[a,mid],[b,p('LIDUS',47,48,3)]],gaps:[{from:'M56-2',to:'NIMTA',reason:'Gap',distanceNm:120}]};
const brokenHtml=buildOfflineBrief({...base,route:broken,image:null});
assert.match(brokenHtml,/НЕПОЛНЫЙ\/НЕОДНОЗНАЧНЫЙ/);
assert.equal((brokenHtml.match(/<polyline /g)||[]).length,2);
console.log('Offline HTML tests passed');
